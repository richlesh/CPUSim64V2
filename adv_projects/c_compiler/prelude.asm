// dcs_lines_to_w(addr) -> wstr joining .dcs lines (terminated by .dci -1)
#def_func dcs_lines_to_w(ap)
    #var    a, sb
    load    a, ap
    #call   vec_new()
    move    sb, r0
    #while  TRUE
        load    r0, a[0]
        #if_cond r0 < 0
            #break
        #end_cond
        #call   sb_add_p(sb, a)
        #call   vec_push(sb, '\n')
        #call   dcs_next(a)
        move    a, r0
    #end_while
    #call   sb_to_w(sb)
#end_func

#def_func prelude_source()
    #call   dcs_lines_to_w(PRELUDE_SRC)
#end_func

