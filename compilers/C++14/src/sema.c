/*
 * sema.c - entities, scopes, name lookup, conversions and overload
 * resolution of the semantic analysis.
 *
 * The parser (parser.c) has its own symbol table, which only knows what
 * kind a name is.  The analysis builds its own: every declaration is
 * processed in order (C++ requires a name to be declared before it is used),
 * and an entity (Ent) records the name's type, its C name and, for
 * constants, its value.
 */

enum { EK_VAR = 1, EK_FUNC, EK_TYPEDEF, EK_NS, EK_ENUMERATOR, EK_ENUM, EK_CLASS, EK_FIELD,
       EK_TEMPLATE,     /* a class template or an alias template */
       EK_FTEMPLATE,    /* a function template (in overload sets, like EK_FUNC) */
       EK_PACK          /* a template parameter pack or a function parameter pack: elems */
};

#define EF_DEFINED  1
#define EF_STATIC   2
#define EF_CLINK    4        /* extern "C": the C name is the C++ name */
#define EF_LIB      8        /* declared in a library header: not written to the C file */
#define EF_SCOPED   16       /* enum class */
#define EF_CONSTEXPR 32
#define EF_INLINE   64
#define EF_PARAM    128
#define EF_ALIAS    256      /* a using-declaration's copy */
#define EF_MEMBER   512      /* a member of a class */
#define EF_CONST_METHOD 1024
#define EF_CTOR     2048
#define EF_DTOR     4096
#define EF_CONV     8192     /* a conversion function */
#define EF_EXPLICIT 16384
#define EF_DELETED  32768
#define EF_DEFAULTED 65536
#define EF_VIRTUAL  131072
#define EF_INDIRECT 262144   /* a parameter of class type: C passes a pointer to the object */
#define EF_IMPLICIT 524288   /* a special member generated by the translator */
#define EF_UNION    1048576
#define EF_NRVO     2097152  /* a local object that is constructed in the function's result */
#define EF_PURE     4194304  /* = 0 */
#define EF_FINAL    8388608
#define EF_OVERRIDE 16777216
#define EF_INJECTED 33554432 /* the injected class name of a class template instance */
#define EF_TINST    67108864 /* an instance of a function template */
#define EF_OOLTRIED 134217728 /* the out-of-line definition of this member was looked for */
#define EF_INCLASS  268435456 /* a member function defined in its class (inline) */

typedef struct Scope2 Scope2;
typedef struct TArg TArg;
typedef struct Tmpl Tmpl;
typedef struct TInst TInst;
typedef struct Lazy Lazy;

static int funcish_kind(int k) { return k == EK_FUNC || k == EK_FTEMPLATE; }

struct Ent {
    int kind;
    Name *name;
    Type *type;
    const char *cname;
    Scope2 *scope;           /* where it is declared */
    Scope2 *members;         /* namespace members, scoped enumerators */
    int has_val;
    i64 cv;                  /* constant value: an enumerator, or a const integral variable with a constant initializer */
    int flags;
    Node **defaults;         /* function: default argument per parameter (0 if none) */
    Ent *overload;           /* the next function of the same name in the same scope */
    const char *prefix;      /* namespace: the mangling prefix of its members ("a_b_") */
    int file, line;
    int access;              /* member: KW_public / KW_protected / KW_private */
    Ent *owner;              /* member: the class */
    struct ClassInfo *ci;    /* class: its members and special functions */
    struct Field *field;     /* EK_FIELD */
    int vslot;               /* virtual function: its slot in the vtable of vowner */
    Ent *vowner;             /* ... the class whose vtable has the slot (0: not virtual) */
    struct Tmpl *tmpl;       /* EK_TEMPLATE / EK_FTEMPLATE */
    struct TInst *inst;      /* an instance of a class or function template: the template and its arguments */
    struct Lazy *lazy;       /* a function whose body is generated when it is first used */
    Ent **elems;             /* EK_PACK: the elements */
    int nelems;
    const char *inst_text;   /* class instance: "<int, 3>" for messages */
    Ent *tmpl_ent;           /* injected class name: the class template */
    Node *cdef, *cfn;        /* constexpr function: the definition and its declarator, for constant evaluation */
    struct TArg **targs;     /* EK_FTEMPLATE: explicitly given template arguments (a copy in an overload set) */
    int ntargs;
};

enum { SS_GLOBAL = 1, SS_NS, SS_BLOCK, SS_CLASS, SS_TMPL };

typedef struct Bucket Bucket;
struct Bucket {
    Ent *head;
    Bucket *next;
};

struct Scope2 {
    Scope2 *parent;
    int kind;
    Bucket **tab;
    int mask;
    Ent *nsent;              /* the namespace entity of SS_NS scopes */
    Scope2 **usings;
    int nusings;
    const char *prefix;      /* mangling prefix of the names declared here */
    Ent *classent;           /* SS_CLASS: the class */
    Scope2 **bases;          /* SS_CLASS: the scopes of the base classes */
    int nbases;
    Ent **dtors;             /* local objects with destructors, in declaration order */
    int ndtors;
    int brk, cont;           /* a break / continue leaves this scope */
    int is_func;             /* the outermost scope of a function body */
    const char *try_prev;    /* the body of a try statement: leaving it restores this handler */
    int catch_end;           /* the body of a catch clause: leaving it ends the catch */
};

typedef struct Field Field;
struct Field {
    Name *name;
    Type *type;
    Node *init;              /* default member initializer */
    int init_form;           /* 1 = braces, 2 = parentheses, 0 = '=' */
    int access;
    Field *next;
    Ent *ent;
};

typedef struct BaseSpec BaseSpec;
struct BaseSpec {
    Ent *cls;
    int access;
    const char *fname;       /* the C member holding the base subobject: __b0, __b1, ... */
    int is_virtual;
};

typedef struct VSlot VSlot;
struct VSlot {
    Name *name;              /* the function's name (nm_dtor for the destructor) */
    Type *ft;
    int is_const;
    Ent *decl;               /* the function that introduced the slot */
};

typedef struct VGroup VGroup;
struct VGroup {
    const char *path;        /* the base subobject that this vtable belongs to ("" for the class itself) */
    Type *x;                 /* its class */
    const char *name;        /* the C name of the vtable */
};

typedef struct ClassInfo ClassInfo;
struct ClassInfo {
    BaseSpec *bases;
    int nbases;
    int poly;                /* has virtual functions (own or inherited) */
    int own_vptr;            /* the class itself declares the vptr member (as its first member) */
    int abstract;
    VSlot *vslots;           /* the slots of this class's own (primary) vtable */
    int nvslots;
    int has_virtual_dtor;
    int is_final;
    Ent **methods;           /* the member functions declared in the class, in order */
    int nmethods;
    struct VGroup *vgroups;  /* the vtables of a polymorphic class */
    int nvgroups;
    int key;                 /* KW_class / KW_struct / KW_union */
    int complete;
    Field *fields, *last_field;
    Scope2 *scope;
    Ent *self;
    Ent *dtor;
    int user_ctor, user_dtor, user_copy_ctor, user_copy_assign;
    int needs_ctor;          /* a constructor call must be written (user constructors, default member initializers, ...) */
    int needs_dtor;          /* a destructor call must be written */
    int nontrivial_copy;
    int aggregate;
    Ent **friend_funcs;
    int nfriend_funcs;
    Ent **friend_classes;
    int nfriend_classes;
    Ent **friend_tmpls;      /* class templates all of whose instances are friends */
    int nfriend_tmpls;
    Ent *implicit_ctor, *implicit_copy, *implicit_assign, *implicit_dtor;
    int user_move_ctor, user_move_assign;
    int decl_copy_ctor, decl_copy_assign;    /* declared by the user, also with = default */
    int copy_deleted, assign_deleted;    /* the copy constructor / copy assignment is deleted (implicitly) */
    Ent *implicit_move, *implicit_massign;
    int is_lambda;           /* the closure type of a lambda expression */
    Ent *lambda_outer;       /* ... that captures this: the class of the enclosing member function */
    int has_array_helpers;
};

static Scope2 *scope2_global, *scope2_cur;

static Scope2 *scope2_new(int kind, Scope2 *parent) {
    Scope2 *s = anew(sizeof(Scope2));
    int size = (kind == SS_BLOCK || kind == SS_TMPL) ? 16 : 256;
    s->kind = kind;
    s->parent = parent;
    s->tab = anew(sizeof(Bucket *) * size);
    s->mask = size - 1;
    s->prefix = parent ? parent->prefix : "";
    return s;
}

/* The table is an array of hash chains; each chain node holds the first entity of a name
   (functions of one name form an overload set through Ent.overload). */
static Ent *sfind(Scope2 *sc, Name *n) {
    Bucket *b;
    for (b = sc->tab[n->hash & sc->mask]; b; b = b->next)
        if (b->head->name == n) return b->head;
    return 0;
}

static void sadd_head(Scope2 *sc, Ent *e) {
    Bucket *b = anew(sizeof(Bucket));
    int h = e->name->hash & sc->mask;
    b->head = e;
    b->next = sc->tab[h];
    sc->tab[h] = b;
}

static void sreplace_head(Scope2 *sc, Name *n, Ent *e) {
    Bucket *b;
    for (b = sc->tab[n->hash & sc->mask]; b; b = b->next)
        if (b->head->name == n) {
            b->head = e;
            return;
        }
}

/* a name in a scope and in the namespaces it uses */
static Ent *lookup_in(Scope2 *sc, Name *n, int depth) {
    Ent *e = sfind(sc, n);
    int i;
    if (e) return e;
    if (depth > 8) return 0;
    for (i = 0; i < sc->nbases; i++) {
        e = lookup_in(sc->bases[i], n, depth + 1);
        if (e) return e;
    }
    for (i = 0; i < sc->nusings; i++) {
        e = lookup_in(sc->usings[i], n, depth + 1);
        if (e) return e;
    }
    return 0;
}

/* an unqualified name: the innermost scope that declares it */
static Ent *lookup_unqual(Scope2 *sc, Name *n) {
    for (; sc; sc = sc->parent) {
        Ent *e = lookup_in(sc, n, 0);
        if (e) return e;
    }
    return 0;
}

static void scope_use(Scope2 *sc, Scope2 *used) {
    int i;
    for (i = 0; i < sc->nusings; i++)
        if (sc->usings[i] == used) return;
    sc->usings = xrealloc(sc->usings, sizeof(Scope2 *) * (sc->nusings + 1));
    sc->usings[sc->nusings++] = used;
}

static Ent *ent_new(int kind, Name *name, Type *type, Scope2 *sc) {
    Ent *e = anew(sizeof(Ent));
    e->kind = kind;
    e->name = name;
    e->type = type;
    e->scope = sc;
    return e;
}

static const char *fmt_str_qn(const char *a, const char *b);

/* the C++ name of an entity with its namespaces, for messages */
static const char *ent_qualified_name(Ent *e) {
    StrBuf sb;
    Scope2 *s;
    const char *parts[16];
    int n = 0, i;
    for (s = e->scope; s && n < 15; s = s->parent)
        if (s->kind == SS_NS && s->nsent) parts[n++] = s->nsent->name->s;
        else if (s->kind == SS_CLASS && s->classent && s->classent->name)
            parts[n++] = s->classent->inst_text ? fmt_str_qn(s->classent->name->s, s->classent->inst_text) : s->classent->name->s;
    sb_init(&sb);
    for (i = n - 1; i >= 0; i--) {
        sb_puts(&sb, parts[i]);
        sb_puts(&sb, "::");
    }
    if (e->name && e->owner && e->name->s[0] == '<' && e->owner->name) {
        /* a constructor or destructor: the name of its class */
        if (strcmp(e->name->s, "<dtor>") == 0) sb_puts(&sb, "~");
        sb_puts(&sb, e->owner->name->s);
    } else sb_puts(&sb, e->name ? e->name->s : "<anonymous>");
    if (e->inst_text) sb_puts(&sb, e->inst_text);
    return sb.s;
}

static const char *class_c_name(Ent *e) {
    return e->cname ? e->cname : (e->name ? e->name->s : "anon");
}

/* ------------------------------------------------------------ values */

/* the result of analysing an expression: its type, the C text, and its category */
typedef struct Val Val;
struct Val {
    Type *t;                 /* the type, never a reference: a reference is a Val with lval = 1 */
    int lval;
    int is_const;            /* an integral constant expression: cv is its value */
    i64 cv;
    int is_null_lit;         /* the literal 0 (a null pointer constant) */
    int static_init;         /* the C text is a constant expression valid in a static initializer */
    const char *c;           /* the C expression, fully parenthesized where needed */
    Ent *fn;                 /* an overload set that is not resolved yet (a function name) */
    Ent *var;                /* the variable that the expression names, if any */
    int is_ref_var;          /* the expression reads through a reference: c already has the dereference */
    const char *this_c;      /* a member function name: the C text of the pointer to the object (0 for static members) */
    Type *this_t;            /* ... and the object's class type with its cv */
    int implicit_this;       /* the object is *this (an unqualified member name) */
    int is_temp;             /* a class prvalue held in a temporary of the function */
    int nonvirtual;          /* a qualified member function name: no virtual dispatch */
    int noop_call;           /* the name of a call that does nothing (a pseudo-destructor)  */
    int xvalue;              /* a class object that is an xvalue: rvalue, but addressable (the result of std::move) */
    Node *braced;            /* a braced-init-list: its elements are in bvals; the target type decides what it means */
    struct Val **bvals;
    int nbvals;
};

static Val *val_new(Type *t, const char *c) {
    Val *v = anew(sizeof(Val));
    v->t = t;
    v->c = c;
    return v;
}

/* ------------------------------------------------------------ conversions */

#define CONV_EXACT 0
#define CONV_PROMOTION 1
#define CONV_CONVERSION 2
#define CONV_USER 3
#define CONV_ELLIPSIS 4
#define CONV_NONE (-1)

/* conversions of class objects (gen.c): same class, converting constructors, conversion functions */
static int class_conversion(Val *v, Type *to);
static int derived_to_base(Type *from, Type *to);       /* is class 'from' derived from class 'to' (a proper base)? */

static int is_null_ptr_const(Val *v) {
    return v->is_null_lit || v->t->kind == TY_NULLPTR;
}

/* qualification: can a pointer to 'from' be converted to a pointer to 'to' by adding cv? */
static int cv_includes(int to, int from) {
    return (to & from) == from;
}

/* the same type, looking through array types (whose cv is that of the elements); returns the cv of both leaves */
static int leaf_same(Type *a, Type *b, int *cva, int *cvb) {
    while (a->kind == TY_ARRAY && b->kind == TY_ARRAY) {
        if (a->len >= 0 && b->len >= 0 && a->len != b->len) return 0;
        a = a->base;
        b = b->base;
    }
    if (a->kind == TY_ARRAY || b->kind == TY_ARRAY) return 0;
    *cva = a->cv;
    *cvb = b->cv;
    return ty_same(a, b);
}

/* is 'a' convertible to the pointer type 'to' (without a user-defined conversion)? returns the rank */
static int ptr_conversion(Type *from, Type *to) {
    Type *fb, *tb;
    if (to->kind != TY_PTR || from->kind != TY_PTR) return CONV_NONE;
    fb = from->base;
    tb = to->base;
    {
        int fc = 0, tc = 0;
        if (leaf_same(fb, tb, &fc, &tc) && cv_includes(tc, fc)) return CONV_EXACT;      /* T* -> const T* */
    }
    if (fb->kind == TY_CLASS && tb->kind == TY_CLASS && !ty_same(fb, tb) && derived_to_base(fb, tb) && cv_includes(tb->cv, fb->cv))
        return CONV_CONVERSION;
    if (tb->kind == TY_VOID && fb->kind != TY_FUNC) return cv_includes(tb->cv, fb->cv) ? CONV_CONVERSION : CONV_NONE;
    return CONV_NONE;
}

/* the rank of converting the value v to the type 'to' (not a reference): CONV_NONE if impossible */
static int value_conversion(Val *v, Type *to) {
    Type *from = v->t;
    to = ty_unqual(to);
    if (v->fn && to->kind == TY_CLASS) return class_conversion(v, to);
    if (v->fn) {
        /* a function name converts to a pointer to function: resolved by the caller */
        return to->kind == TY_PTR && to->base->kind == TY_FUNC ? CONV_EXACT : CONV_NONE;
    }
    if (from->kind == TY_ARRAY) from = ty_ptr(from->base);
    else if (from->kind == TY_FUNC) from = ty_ptr(from);
    if (ty_same(from, to)) return CONV_EXACT;
    if (from->kind == TY_CLASS || to->kind == TY_CLASS) return class_conversion(v, to);
    if (to->kind == TY_PTR) {
        int r;
        if (is_null_ptr_const(v)) return CONV_CONVERSION;
        r = ptr_conversion(from, to);
        if (r != CONV_NONE) return r;
        return CONV_NONE;
    }
    if (to->kind == TY_BOOL) {
        if (ty_is_scalar(from) && from->kind != TY_NULLPTR) return CONV_CONVERSION;
        if (from->kind == TY_PTR) return CONV_CONVERSION;
        return CONV_NONE;
    }
    if (ty_is_arith(to)) {
        if (ty_is_arith(from)) {
            if (ty_is_integral(to) && ty_is_integral(from) && ty_same(ty_promote(from), to)) return CONV_PROMOTION;
            if (to->kind == TY_DOUBLE && from->kind == TY_FLOAT) return CONV_PROMOTION;
            return CONV_CONVERSION;
        }
        if (from->kind == TY_ENUM && !(from->ent->flags & EF_SCOPED)) {
            if (ty_is_integral(to) && ty_same(to, T_INT)) return CONV_PROMOTION;
            return CONV_CONVERSION;
        }
        return CONV_NONE;
    }
    if (to->kind == TY_ENUM) return CONV_NONE;
    return CONV_NONE;
}

static int braced_conversion(Val *bv, Type *p);

/* the rank of binding the argument v to a parameter of type p (which may be a reference) */
static int arg_conversion(Val *v, Type *p) {
    if (v->braced) return braced_conversion(v, p);
    if (p->kind == TY_REF || p->kind == TY_RREF) {
        Type *tb = p->base;
        int r;
        if (p->kind == TY_REF && !(tb->cv & CV_CONST)) {
            /* a non-const lvalue reference binds an lvalue of the same type */
            if (!v->lval || v->fn) return CONV_NONE;
            if (ty_same(v->t, tb) && cv_includes(tb->cv, v->t->cv)) return CONV_EXACT;
            if (v->t->kind == TY_CLASS && tb->kind == TY_CLASS && derived_to_base(v->t, tb) && cv_includes(tb->cv, v->t->cv)) return CONV_CONVERSION;
            return CONV_NONE;
        }
        if (p->kind == TY_RREF && v->lval && !v->fn) return CONV_NONE;
        if (ty_same(v->t, tb) && cv_includes(tb->cv, v->t->cv)) return CONV_EXACT;
        if (v->t->kind == TY_CLASS && tb->kind == TY_CLASS && derived_to_base(v->t, tb) && cv_includes(tb->cv, v->t->cv)) return CONV_CONVERSION;
        if (v->t->kind == TY_ARRAY && tb->kind == TY_ARRAY && ty_same(v->t, tb)) return CONV_EXACT;
        r = value_conversion(v, tb);
        return r == CONV_NONE ? CONV_NONE : (r > CONV_CONVERSION ? CONV_CONVERSION : CONV_CONVERSION);
    }
    return value_conversion(v, p);
}

/* 1 if the argument is an rvalue bound to an lvalue reference: binding it to an rvalue reference is better */
static int arg_tiebreak(Val *v, Type *p) {
    if (p->kind == TY_REF && !v->lval && !v->fn && (p->base->cv & CV_CONST)) return 1;
    /* an lvalue binds better to a reference to the same type with less cv-qualification */
    if (p->kind == TY_REF && v->lval && !v->fn && (p->base->cv & CV_CONST) && !(v->t->cv & CV_CONST)) return 1;
    /* by value: as good as the const reference (only a T& to the same type is better) */
    if (!ty_is_ref(p) && v->lval && !v->fn && !(v->t->cv & CV_CONST)) return 1;
    return 0;
}

/* ------------------------------------------------------------ overloads */

static int func_min_args(Ent *f) {
    int n = f->type->nparams;
    while (n > 0 && f->defaults && f->defaults[n - 1]) n--;
    return n;
}

static int func_viable_count(Ent *f, int nargs) {
    if (nargs < func_min_args(f)) return 0;
    if (nargs > f->type->nparams && !f->type->variadic) return 0;
    return 1;
}

/* templates (tmpl.c) */
static Ent *deduce_function(Ent *tf, Val **args, int nargs, Type *objt);
static int template_tiebreak(Ent *a, Ent *b);

/* compares two candidates for the arguments: <0 if a is better, >0 if b is, 0 if neither */
static int compare_candidates(Ent *a, Ent *b, int *ra, int *rb, int nargs) {
    int i, a_better = 0, b_better = 0;
    for (i = 0; i <= nargs; i++) {
        if (ra[i] < rb[i]) a_better = 1;
        else if (rb[i] < ra[i]) b_better = 1;
    }
    if (a_better && !b_better) return -1;
    if (b_better && !a_better) return 1;
    if (!a_better && !b_better && ((a->flags | b->flags) & EF_TINST)) return template_tiebreak(a, b);
    return 0;
}

/* picks the function of the overload set that the arguments call; 0 if none is viable
   (*ambiguous is set if several are viable and none is better than all the others) */
#define MAX_CANDS 64

static Ent *resolve_overload_obj(Ent *set, Val **args, int nargs, Type *objt, int *ambiguous);

static Ent *resolve_overload(Ent *set, Val **args, int nargs, int *ambiguous) {
    return resolve_overload_obj(set, args, nargs, 0, ambiguous);
}

/* objt: the type of the object of a member function call (its cv matters), or 0 */
static Ent *resolve_overload_obj(Ent *set, Val **args, int nargs, Type *objt, int *ambiguous) {
    Ent *cands[MAX_CANDS];
    Ent *flist[MAX_CANDS];
    int *ranks[MAX_CANDS];
    int n = 0, i, j, nf = 0, fi;
    Ent *f;
    *ambiguous = 0;
    for (f = set; f && nf < MAX_CANDS; f = f->overload) {
        if (f->kind == EK_FTEMPLATE) {
            Ent *inst = deduce_function(f, args, nargs, objt);
            if (inst) flist[nf++] = inst;
        } else if (f->kind == EK_FUNC) flist[nf++] = f;
    }
    for (fi = 0; fi < nf && n < MAX_CANDS; fi++) {
        int *r, ok = 1;
        f = flist[fi];
        if (f->kind != EK_FUNC || !func_viable_count(f, nargs)) continue;
        if (objt && (f->flags & EF_MEMBER) && (objt->cv & CV_CONST) && !(f->flags & EF_CONST_METHOD)) continue;
        r = anew(sizeof(int) * (nargs + 2));
        for (i = 0; i < nargs; i++) {
            int c = i < f->type->nparams ? arg_conversion(args[i], f->type->params[i]) : CONV_ELLIPSIS;
            if (c == CONV_NONE) {
                ok = 0;
                break;
            }
            r[i] = c * 2 + (i < f->type->nparams ? arg_tiebreak(args[i], f->type->params[i]) : 0);
        }
        if (!ok) continue;
        /* the implicit object argument: a const method called on a non-const object is a worse match */
        r[nargs] = (objt && (f->flags & EF_MEMBER) && (f->flags & EF_CONST_METHOD) && !(objt->cv & CV_CONST)) ? 1 : 0;
        cands[n] = f;
        ranks[n] = r;
        n++;
    }
    for (i = 0; i < n; i++) {
        int best = 1;
        for (j = 0; j < n; j++)
            if (j != i && compare_candidates(cands[i], cands[j], ranks[i], ranks[j], nargs) >= 0) best = 0;
        if (best) return cands[i];
    }
    if (n > 0) *ambiguous = 1;
    return 0;
}

/* the function of an overload set whose type is exactly ft (for &f with a target type, redeclarations) */
static Ent *find_function(Ent *set, Type *ft) {
    Ent *f;
    int i;
    for (f = set; f; f = f->overload) {
        if (f->kind != EK_FUNC || f->type->nparams != ft->nparams || f->type->variadic != ft->variadic) continue;
        for (i = 0; i < ft->nparams; i++)
            if (!ty_same(ty_adjust_param(f->type->params[i]), ty_adjust_param(ft->params[i]))) break;
        if (i == ft->nparams) return f;
    }
    return 0;
}
