/*
 * translate.c - the C text of the whole program.
 */

static const char **unit_names = 0;    /* the other units of the program (their dynamic initialization runs before main) */
static int nunit_names = 0;

/* the C name part for a source file: its base name without the extension */
static const char *unit_init_name(const char *path) {
    const char *b = base_name(path);
    StrBuf sb;
    int i;
    sb_init(&sb);
    for (i = 0; b[i] && b[i] != '.'; i++) {
        int c = b[i];
        sb_putc(&sb, (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') ? c : '_');
    }
    return sb.s;
}

/* the C text of the whole program */
static void translate(Node *tree, const char *outpath, FILE *f) {
    Ent *m;
    Name *main_name = intern_str("main");
    size_t n = strlen(outpath), i;
    StrBuf init_temps;
    char *dir = xalloc(n + 1);
    memcpy(dir, outpath, n);
    for (i = n; i > 0 && dir[i - 1] != '/'; i--) ;
    dir[i] = 0;
    out_dir = dir;
    sb_init(&out_head);
    sb_init(&out_body);
    sb_init(&out_init);
    sb_init(&init_temps);
    sb_init(&pending_helpers);
    sb_init(&out_tdesc_decl);
    sb_init(&out_tdesc_def);
    sb_init(&late_defs);
    nm_ctor = intern_str("<ctor>");
    nm_dtor = intern_str("<dtor>");
    out = &out_body;
    temps = &init_temps;
    scope2_global = scope2_new(SS_GLOBAL, 0);
    scope2_cur = scope2_global;
    process_toplevel_list(tree);
    if (uses_typeid && typeinfo_cls) {
        /* a std::type_info object for every descriptor: typeid(expression) finds it through the vtable */
        TDesc *d;
        for (d = tdescs; d; d = d->next) {
            sb_printf(&out_tdesc_def, "static %s __cppc_tio%d = { (const void *)&__cppc_ti%d };\n", class_tag(typeinfo_cls), d->id, d->id);
            sb_printf(&out_init, "__cppc_ti%d.tio = &__cppc_tio%d;\n", d->id, d->id);
        }
        dyn_init_count++;
    }
    sb_puts(&out_head, "/* generated by cppc */\n#include <stdlib.h>\n#include <string.h>\nstatic void __cppc_pure(void) { abort(); }\n");
    for (i = 0; i < (size_t)pp_c_include_count; i++) sb_printf(&out_head, "#include <%s>\n", pp_c_includes[i]);
    if (uses_exc || ntdesc > 0) {
        sb_puts(&out_head, "struct __cppc_type { const char *name; int kind; int nbases; const struct __cppc_type *const *bases; void *(*up)(void *, int); void (*dtor)(void *); const struct __cppc_type *pointee; void *tio; };\n");
        sb_puts(&out_head, out_tdesc_decl.s);
        sb_puts(&out_head, rtti_runtime_text);
    }
    if (multi_unit) uses_exc = 1;            /* an exception may pass through the objects of any unit */
    if (uses_exc) sb_puts(&out_head, unit_secondary ? "#define __CPPC_SHARED extern\n" : "#define __CPPC_SHARED\n");
    sb_puts(&out_head, uses_exc ? exc_runtime_text : exc_noop_text);
    fputs(out_head.s, f);
    fputs(out_body.s, f);
    fputs("\n#line 1 \"<cppc>\"\n", f);
    fputs(out_tdesc_def.s, f);
    fputs("\n#line 1 \"<cppc>\"\n", f);
    fputs(pending_helpers.s, f);
    fputs(late_defs.s, f);
    if (dyn_init_count > 0 || unit_secondary) {
        if (unit_secondary) fprintf(f, "void __cppc_init_%s(void) {\n", unit_init_name(files[0].path));
        else fputs("static void __cppc_init(void) {\n", f);
        fputs(init_temps.s, f);
        fputs(out_init.s, f);
        fputs("}\n", f);
    }
    m = lookup_in(scope2_global, main_name, 0);
    if (unit_secondary) {
        if (m && m->kind == EK_FUNC) serr(0, "main() is defined in a unit that is not the first source file");
        return;
    }
    if (m && m->kind == EK_FUNC) {
        int two = m->type->nparams == 2, k;
        StrBuf inits;
        sb_init(&inits);
        for (k = 0; k < nunit_names; k++) {
            fprintf(f, "void __cppc_init_%s(void);\n", unit_init_name(unit_names[k]));
            sb_printf(&inits, "        __cppc_init_%s();\n", unit_init_name(unit_names[k]));
        }
        if (dyn_init_count > 0) sb_puts(&inits, "        __cppc_init();\n");
        if (uses_exc)
            fprintf(f, "int main(int argc, char **argv) {\n    struct __cppc_handler __h;\n    int __r;\n    __h.prev = 0;\n    __h.ctop = 0;\n    __cppc_htop = &__h;\n"
                       "    if (setjmp(__h.jb) == 0) {\n%s        __r = __cppc_main(%s);\n        __cppc_htop = 0;\n        return __r;\n    }\n    __cppc_terminate();\n    return 1;\n}\n",
                    inits.s, two ? "argc, argv" : "");
        else
            fprintf(f, "int main(int argc, char **argv) {\n%s    return __cppc_main(%s);\n}\n", inits.s, two ? "argc, argv" : "");
    }
}
