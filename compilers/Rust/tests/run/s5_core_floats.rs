use std::f64::consts::{E, PI};
fn main() {
    let x = -2.75f64;
    println!("{} {} {} {} {}", x.abs(), x.floor(), x.ceil(), x.round(), x.trunc());
    println!("{} {} {} {}", 2.5f64.round(), (-2.5f64).round(), 0.49999f64.round(), 1e15f64.round());
    println!("{} {} {}", 2.0f64.powi(10), 2.0f64.powi(-2), 1.5f64.powi(3));
    println!("{} {}", 2.0f64.powf(0.5), 9.0f64.powf(1.5));
    println!("{:.6} {:.6}", 8.0f64.powf(1.0 / 3.0), 10.0f64.powf(-2.0));
    println!("{} {}", 2.0f64.sqrt(), 16.0f64.sqrt());
    println!("{} {}", 1.0f64.min(2.0), 1.0f64.max(2.0));
    println!("{} {}", 5.5f64.clamp(0.0, 3.0), (-1.0f64).clamp(0.0, 3.0));
    println!("{} {}", f64::NAN.is_nan(), 1.0f64.is_nan());
    println!("{:.5} {:.5}", PI, E);
    println!("{}", PI);
    println!("{}", E);
    println!("{:?} {:?}", 1.0f64, 0.1f64 + 0.2);
    println!("{}", f64::MAX > 1e300);
    println!("{} {}", f64::INFINITY, -f64::INFINITY);
    println!("{}", (2.0f64).powf(10.0) as i32);
    println!("{} {}", 7.0f64 / 2.0, (7.0f64 / 2.0).fract());
    println!("{:.3}", (1.0f64).exp());
    println!("{:.3} {:.3}", (100.0f64).ln(), (100.0f64).log10());
    println!("{:.3} {:.3} {:.3}", (1.0f64).sin(), (1.0f64).cos(), (1.0f64).tan());
    println!("{:.3} {:.3}", (1.0f64).atan(), (1.0f64).atan2(2.0));
    println!("{:.4} {:.4}", 3.0f64.hypot(4.0), 8.0f64.cbrt());
    println!("{}", 3.7f64 as i32);
    println!("{}", -3.7f64 as i32);
    println!("{}", 1e10f64 as u8);
    println!("{} {}", 2.0f64.mul_add(3.0, 1.0), 10.0f64.log2());
    println!("{} {}", 1.0f64.copysign(-2.0), 3.0f64.signum());
    println!("{}", 90.0f64.to_radians());
    println!("{}", PI.to_degrees());
    let v = vec![3.5, -1.0, 2.25];
    let mx = v.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
    let mn = v.iter().cloned().fold(f64::INFINITY, f64::min);
    println!("{} {}", mx, mn);
    let mut s = v.clone();
    s.sort_by(|a, b| a.partial_cmp(b).unwrap());
    println!("{:?}", s);
    println!("{}", v.iter().map(|x| x * x).sum::<f64>().sqrt());
}
