fn main() {
    let v = vec![1, 2, 3, 4, 5, 6, 7, 8];
    let (ev, od): (Vec<i32>, Vec<i32>) = v.iter().partition(|&&x| x % 2 == 0);
    println!("{:?} {:?}", ev, od);
    let fm: Vec<i32> = v.iter().take(3).flat_map(|&x| vec![x, x * 10]).collect();
    println!("{:?}", fm);
    let nested = vec![vec![1, 2], vec![], vec![3]];
    let fl: Vec<i32> = nested.into_iter().flatten().collect();
    println!("{:?}", fl);
    let opts = vec![Some(1), None, Some(3)];
    let fo: Vec<i32> = opts.into_iter().flatten().collect();
    println!("{:?}", fo);
    let mut seen = 0;
    let s: i32 = v.iter().inspect(|&&x| seen += x).map(|x| x * 2).sum();
    println!("{} {}", s, seen);
    let sc: Vec<i32> = v.iter().scan(0, |acc, &x| { *acc += x; if *acc > 20 { None } else { Some(*acc) } }).collect();
    println!("{:?}", sc);
    let words = ["apple", "fig", "banana", "kiwi"];
    println!("{:?}", words.iter().max_by(|a, b| a.len().cmp(&b.len())));
    println!("{:?}", words.iter().min_by_key(|w| w.len()));
    println!("{:?}", words.iter().max_by_key(|w| w.len()));
    println!("{:?}", words.iter().position(|&w| w == "banana"));
    println!("{:?}", words.iter().rposition(|&w| w.len() == 4));
    println!("{} {}", v.iter().any(|&x| x > 7), v.iter().all(|&x| x > 1));
    let fs = vec![1.5, 2.5, 3.0];
    let sf: f64 = fs.iter().sum();
    let pf: f64 = fs.iter().product();
    let sf2: f64 = fs.iter().map(|x| x * 2.0).sum();
    println!("{} {} {}", sf, pf, sf2);
    let (aa, bb): (Vec<i32>, Vec<char>) = vec![(1, 'a'), (2, 'b')].into_iter().unzip();
    println!("{:?} {:?}", aa, bb);
    let cy: Vec<i32> = [1, 2, 3].iter().cloned().cycle().take(7).collect();
    println!("{:?}", cy);
    println!("{:?} {:?}", v.iter().last(), v.iter().nth(2));
    let mut it = v.iter();
    println!("{:?} {:?}", it.nth(1), it.nth(1));
    let sb: Vec<i32> = (0..20).step_by(6).collect();
    println!("{:?}", sb);
    let sb2: Vec<&i32> = v.iter().step_by(3).collect();
    println!("{:?}", sb2);
    println!("{:?}", (1..=4).rev().collect::<Vec<i32>>());
    println!("{}", (1..=5).product::<i32>());
    println!("{:?}", v.iter().rev().take(2).collect::<Vec<_>>());
    println!("{:?}", v.iter().copied().reduce(|a, b| a.max(b)));
    println!("{:?}", v.iter().min());
    let total: i32 = v.iter().rev().enumerate().map(|(i, x)| i as i32 * x).sum();
    println!("{}", total);
    println!("{:?}", v.iter().map(|x| x * x).filter(|x| x % 2 == 1).collect::<Vec<_>>());
    println!("{}", v.iter().count());
    let strs: Vec<String> = v.iter().map(|x| x.to_string()).collect();
    println!("{}", strs.join(","));
}
