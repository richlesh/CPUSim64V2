// println! format specs
fn main() {
    let n = 42;
    let neg = -7;
    let pi = 3.14159265;
    let s = "abc";
    println!("[{}]", n);
    println!("[{:?}]", n);
    println!("[{:5}]", n);
    println!("[{:<5}]", n);
    println!("[{:>5}]", n);
    println!("[{:^5}]", n);
    println!("[{:05}]", n);
    println!("[{:+}]", n);
    println!("[{:05}]", neg);
    println!("[{:*>6}]", n);
    println!("[{:->6}]", s);
    println!("[{:8}]", s);
    println!("[{:<8}]", s);
    println!("[{:>8}]", s);
    println!("[{:^8}]", s);
    println!("[{:.2}]", s);
    println!("[{:>8.3}]", pi);
    println!("[{:8.3}]", pi);
    println!("[{:<8.1}]", pi);
    println!("[{:.0}]", pi);
    println!("[{}]", pi);
    println!("[{:?}]", 1.0f64);
    println!("[{}]", 1.0f64);
    println!("[{:x}]", 255);
    println!("[{:X}]", 255);
    println!("[{:#x}]", 255);
    println!("[{:08b}]", 37u8);
    println!("[{:#b}]", 5);
    println!("[{:o}]", 64);
    println!("[{:#010x}]", 48879);
    println!("[{:?}]", "quo\"te\n");
    println!("[{:?}]", 'x');
    println!("[{:?}]", '\'');
    println!("[{}]", true);
    println!("[{:?}]", ());
    println!("[{:?}]", (1, "two", 3.5));
    println!("[{:?}]", [1, 2, 3]);
    println!("[{:?}]", Some(5));
    println!("[{:?}]", None::<i32>);
    println!("[{:#?}]", (1, 2));
    println!("{0} {1} {0}", "a", "b");
    let w = 7;
    println!("[{:w$}] [{:>1$}] [{:.*}]", n, 6, 2, pi);
    println!("[{n}] [{s:>5}] [{pi:.1}]");
    println!("{{}} {{{}}}", n);
    println!("{}", u64::MAX);
    println!("{:?}", i64::MIN);
    let e = format!("{}-{}", n, s);
    println!("{}", e);
    eprintln!("to stderr");
}
